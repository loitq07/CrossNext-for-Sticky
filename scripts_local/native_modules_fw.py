# Firmware side of native modules (tools_local/native_modules/build_module.py).
#
# 1. Stamps a fresh module ABI id into NativeModuleAbi.generated.h. A module is
#    compiled against this tree's headers, so a rebuilt firmware is a new ABI
#    and the loader refuses modules from another build.
# 2. Generates the export table modules resolve against
#    (NativeModuleExports.generated.cpp): every firmware function/data symbol a
#    module imports, plus the weak data objects (inline statics) a module must
#    share with the firmware. Names are stored as two 32-bit FNV-1a hashes, not
#    strings, to keep the table at 12 bytes a symbol.
# 3. Keeps those symbols alive through --gc-sections and pulls them out of
#    library archives (EXTERN in an implicit linker script).
import os
import secrets

Import("env")  # noqa: F821

root = env["PROJECT_DIR"]  # noqa: F821
gen_dir = os.path.join(root, "src", "apps_local", "modules")
keep = os.path.join(root, "tools_local", "native_modules", "keep_symbols.txt")


def fnv1a(name, seed):
    h = seed
    for b in name.encode("utf-8"):
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h


SEED_A = 0x811C9DC5
SEED_B = 0x2545F491

abi = secrets.randbits(32) | 1
with open(os.path.join(gen_dir, "NativeModuleAbi.generated.h"), "w", encoding="utf-8") as f:
    f.write("// Generated by scripts_local/native_modules_fw.py on every build. Do not edit.\n")
    f.write("#pragma once\n#define STICKY_MODULE_ABI 0x%08xu\n" % abi)
print("native modules: ABI 0x%08x" % abi)

# keep_symbols.txt: "U name" = a firmware symbol a module imports (must exist,
# kept through gc); "S name" = a weak data object a module shares with the
# firmware when the firmware has one (weak reference only).
syms, imports = [], []
if os.path.exists(keep):
    for line in open(keep, encoding="utf-8"):
        line = line.strip()
        if len(line) > 2 and line[1] == " ":
            syms.append(line[2:])
            if line[0] == "U":
                imports.append(line[2:])
syms = sorted(set(syms))

entries = sorted((fnv1a(s, SEED_A), fnv1a(s, SEED_B), s) for s in syms)
for a, b in zip(entries, entries[1:]):
    if a[0] == b[0] and a[1] == b[1]:
        raise SystemExit("native modules: hash collision between %s and %s" % (a[2], b[2]))

out = os.path.join(gen_dir, "NativeModuleExports.generated.cpp")
lines = [
    "// Generated by scripts_local/native_modules_fw.py from tools_local/native_modules/keep_symbols.txt.",
    "// Do not edit. Weak references: a symbol this firmware does not define resolves",
    "// to 0 and the module falls back to its own copy.",
    "#include <cstddef>",
    "#include <cstdint>",
    "",
    "#include \"NativeModuleExports.h\"",
    "",
    "extern \"C\" {",
]
for i, (_, _, s) in enumerate(entries):
    lines.append('extern char nm_sym_%d __asm__("%s") __attribute__((weak));' % (i, s))
lines += ["}", "", "namespace native_module {", "const ExportEntry kExports[] = {"]
for i, (ha, hb, s) in enumerate(entries):
    lines.append("    {0x%08xu, 0x%08xu, &nm_sym_%d},  // %s" % (ha, hb, i, s[:80]))
if not entries:
    lines.append("    {0u, 0u, nullptr},")
lines += ["};", "const size_t kExportCount = %d;" % len(entries), "}  // namespace native_module", ""]
new_text = "\n".join(lines)
if not os.path.exists(out) or open(out, encoding="utf-8").read() != new_text:
    with open(out, "w", encoding="utf-8") as f:
        f.write(new_text)
print("native modules: exporting %d symbols to modules" % len(entries))

if imports:
    # An implicit linker script rather than one -u per symbol: hundreds of
    # flags overflow the Windows command line. EXTERN() is -u.
    build_dir = env.subst("$BUILD_DIR")  # noqa: F821
    os.makedirs(build_dir, exist_ok=True)
    keep_ld = os.path.join(build_dir, "native_modules_keep.ld")
    with open(keep_ld, "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts_local/native_modules_fw.py */\n")
        for s in imports:
            f.write('EXTERN("%s")\n' % s)
    env.Append(LINKFLAGS=[keep_ld.replace("\\", "/")])  # noqa: F821

#!/usr/bin/env python3
"""Embed the Phosphor icons the web UI uses, so the pages work without Internet.

The device pages used to load https://unpkg.com/@phosphor-icons/web, so every
icon vanished whenever the browser had no Internet access -- the usual case
when a phone or laptop joins the Sticky's own hotspot. This script subsets the
Phosphor "regular" font to the icons actually referenced in
src/network/html (class="ph ph-<name>") and writes
src/network/html/shared/PhosphorIcons.css.inc: an @font-face with the subset
WOFF2 inlined as a data URI, plus one rule per icon. Pages include it inside
their <style> block via <!--#include file="shared/PhosphorIcons.css.inc" -->.

Re-run after adding a new icon to a page:

    npm pack @phosphor-icons/web@2.1.1   # or: npm i @phosphor-icons/web@2.1.1
    python scripts/generate_phosphor_icons.py <package>/src/regular

--check exits non-zero if the committed include is missing an icon a page
uses (no font tools needed for that).

Requires fontTools and brotli (pip install fonttools brotli) when generating.
Phosphor Icons are MIT-licensed (c) Phosphor Icons; see THIRD-PARTY-NOTICES.md.
"""
import base64
import io
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HTML_DIR = ROOT / "src" / "network" / "html"
OUT = HTML_DIR / "shared" / "PhosphorIcons.css.inc"
WEIGHT_CLASSES = {"ph-thin", "ph-light", "ph-bold", "ph-fill", "ph-duotone"}


def used_icons():
    names = set()
    for path in list(HTML_DIR.glob("*.html")) + list((HTML_DIR / "shared").glob("*.inc")):
        if path == OUT:
            continue
        names.update(re.findall(r"\bph-[a-z0-9]+(?:-[a-z0-9]+)*\b", path.read_text(encoding="utf-8")))
    return sorted(names - WEIGHT_CLASSES)


def check():
    have = set(re.findall(r"\.ph\.(ph-[a-z0-9-]+):before", OUT.read_text(encoding="utf-8"))) if OUT.exists() else set()
    missing = [n for n in used_icons() if n not in have]
    if missing:
        print("Missing from PhosphorIcons.css.inc: " + ", ".join(missing))
        print("Re-run scripts/generate_phosphor_icons.py <phosphor>/src/regular")
        return 1
    print("PhosphorIcons.css.inc covers all %d icons" % len(have))
    return 0


def generate(regular_dir):
    from fontTools import subset
    from fontTools.ttLib import TTFont

    css = (regular_dir / "style.css").read_text(encoding="utf-8")
    codepoints = {m.group(1): m.group(2) for m in re.finditer(r'\.ph\.(ph-[a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css)}
    icons = used_icons()
    unknown = [n for n in icons if n not in codepoints]
    if unknown:
        sys.exit("Not Phosphor icons (typo?): " + ", ".join(unknown))

    font = TTFont(regular_dir / "Phosphor.ttf")
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = []  # icons are addressed by codepoint; drop the name ligatures
    options.name_IDs = []
    options.notdef_outline = False
    options.hinting = False
    options.desubroutinize = True
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=[int(codepoints[n], 16) for n in icons])
    subsetter.subset(font)
    buf = io.BytesIO()
    font.flavor = "woff2"
    font.save(buf)
    woff2 = base64.b64encode(buf.getvalue()).decode("ascii")

    rules = "\n".join(f'.ph.{n}:before{{content:"\\{codepoints[n]}"}}' for n in icons)
    OUT.write_text(
        "/* Phosphor Icons 2.1.1 (regular), MIT, Copyright (c) 2020-2021 Phosphor Icons.\n"
        "   Subset of the icons the pages use; see THIRD-PARTY-NOTICES.md.\n"
        "   Generated by scripts/generate_phosphor_icons.py; do not edit by hand. */\n"
        "@font-face{font-family:\"Phosphor\";src:url(data:font/woff2;base64," + woff2 + ") format(\"woff2\");"
        "font-weight:normal;font-style:normal;font-display:block}\n"
        ".ph{font-family:\"Phosphor\"!important;speak:never;font-style:normal;font-weight:normal;font-variant:normal;"
        "text-transform:none;line-height:1;-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}\n"
        + rules + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(icons)} icons, {len(buf.getvalue())} byte font")


if __name__ == "__main__":
    if len(sys.argv) == 2 and sys.argv[1] == "--check":
        sys.exit(check())
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    generate(Path(sys.argv[1]))

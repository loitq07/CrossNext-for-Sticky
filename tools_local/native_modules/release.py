"""One-shot release of the firmware plus every native module built for it.

  python release.py [--publish <appstore checkout>]

1. compile all modules, refresh keep_symbols.txt (the firmware export list)
2. build the firmware (stamps a new module ABI, exports what modules import)
3. link every module against that build
4. with --publish: copy the modules to <checkout>/modules/<abi>/<folder>/ (the
   App Store fetches from there), commit, and push the `appstore` branch

The interface language packs (tools_local/sticky_language_packs.py, English is
the only language in flash) are built into OUT/languages/ first and published
the same way: their string keys follow the firmware, so each build gets its own.

A module only runs on the firmware it was linked with, so steps 2-4 always go
together: flash the firmware from this run and publish these modules with it.
"""

import json
import os
import re
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
WORKSPACE = os.path.abspath(os.path.join(ROOT, ".."))
PY = sys.executable
ENV = os.environ.get("PIO_ENV", "gh_release_sticky")
OUT = os.environ.get("MODULE_OUT", os.path.join(ROOT, ".pio", "module-release"))
ABI_HEADER = os.path.join(ROOT, "src", "apps_local", "modules", "NativeModuleAbi.generated.h")


def step(cmd, **kw):
    print("$", " ".join(cmd), flush=True)
    r = subprocess.run(cmd, **kw)
    if r.returncode != 0:
        sys.exit("failed: %s" % " ".join(cmd))


def compiledb_stale():
    """compiledb only supplies module compile flags, and it costs a full
    dependency scan. Reuse it while it was generated by this checkout after the
    last change to platformio.ini or the build scripts; build_module.py
    recompiles any object whose flags differ anyway. FORCE_COMPILEDB=1 always
    regenerates."""
    db = os.path.join(ROOT, "compile_commands.json")
    if os.environ.get("FORCE_COMPILEDB") or not os.path.exists(db):
        return True
    inputs = [os.path.join(ROOT, "platformio.ini")]
    for d in ("scripts", "scripts_local"):
        base = os.path.join(ROOT, d)
        inputs += [os.path.join(base, f) for f in os.listdir(base) if f.endswith(".py")] if os.path.isdir(base) else []
    if os.path.getmtime(db) < max(os.path.getmtime(p) for p in inputs if os.path.exists(p)):
        return True
    try:
        with open(db, encoding="utf-8") as f:
            entries = json.load(f)
    except (OSError, ValueError):
        return True
    root = os.path.normcase(os.path.abspath(ROOT))
    return not any(os.path.normcase(os.path.abspath(e.get("directory", ""))) == root for e in entries[:1])


def update_catalog_sizes():
    """Store sizes from the previous link (a relink only changes the ABI word)."""
    path = os.path.join(ROOT, "src", "apps_local", "appstore", "AppStoreCatalog.h")
    text = open(path, encoding="utf-8").read()
    for folder in (os.listdir(OUT) if os.path.isdir(OUT) else []):
        for f in os.listdir(os.path.join(OUT, folder)):
            n = os.path.getsize(os.path.join(OUT, folder, f))
            text = re.sub(r'("%s", )\d+, "[^"]*"(, true)' % re.escape(f),
                          lambda m: '%s%d, "%.1f KB"%s' % (m.group(1), n, n / 1024, m.group(2)), text)
    open(path, "w", encoding="utf-8").write(text)


def main():
    publish = None
    if "--publish" in sys.argv:
        publish = sys.argv[sys.argv.index("--publish") + 1]

    os.environ["MODULE_OUT"] = OUT
    os.environ.setdefault("PLATFORMIO_CORE_DIR", os.path.join(WORKSPACE, ".platformio"))
    # Generate flags for this checkout: the workspace wrapper may build a
    # different worktree, which would produce an incompatible firmware ABI.
    if compiledb_stale():
        step([PY, "-m", "platformio", "run", "-e", ENV, "-t", "compiledb"], cwd=ROOT)
    else:
        print("compile_commands.json is current for this checkout; skipping compiledb", flush=True)
    template = os.path.join(HERE, "compile_template.json")
    if os.path.exists(template):
        os.remove(template)
    step([PY, os.path.join(HERE, "build_module.py"), "objects"])
    step([PY, os.path.join(ROOT, "tools_local", "sticky_language_packs.py"), os.path.join(OUT, "languages")])
    update_catalog_sizes()
    step([PY, "-m", "platformio", "run", "-e", ENV], cwd=ROOT)
    step([PY, os.path.join(HERE, "build_module.py"), "link"])
    abi = re.search(r"0x([0-9a-fA-F]+)", open(ABI_HEADER, encoding="utf-8").read()).group(1).lower()
    print("module ABI:", abi)

    if publish:
        dest = os.path.join(publish, "modules", abi)
        for folder in os.listdir(OUT):
            os.makedirs(os.path.join(dest, folder), exist_ok=True)
            for f in os.listdir(os.path.join(OUT, folder)):
                shutil.copy2(os.path.join(OUT, folder, f), os.path.join(dest, folder, f))
        step(["git", "-C", publish, "add", "modules/" + abi])
        step(["git", "-C", publish, "commit", "-m",
              "Native modules for firmware ABI " + abi + chr(10) + chr(10) +
              "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"])
        step(["git", "-C", publish, "push", "github", "appstore"])
        print("published modules/%s" % abi)


if __name__ == "__main__":
    main()

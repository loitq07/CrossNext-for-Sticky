// The art for a FEN letter, either colour, or nullptr.
inline const char* const* pieceArt(char p) {
  switch (p) {
    case 'k': case 'K': return PIECE_KING;
    case 'q': case 'Q': return PIECE_QUEEN;
    case 'r': case 'R': return PIECE_ROOK;
    case 'b': case 'B': return PIECE_BISHOP;
    case 'n': case 'N': return PIECE_KNIGHT;
    case 'p': case 'P': return PIECE_PAWN;
    default: return nullptr;
  }
}

// Whether the art inks (r, c), and for a white piece only its edge: ink with a blank or the edge
// on one of its four sides (outline).
inline bool pieceInk(const char* const* art, int r, int c, bool white) {
  auto on = [&](int rr, int cc) {
    return rr >= 0 && rr < kPieceSize && cc >= 0 && cc < kPieceSize && art[rr][cc] == '#';
  };
  if (!on(r, c)) return false;
  if (!white) return true;
  return !(on(r + 1, c) && on(r - 1, c) && on(r, c + 1) && on(r, c - 1));
}

